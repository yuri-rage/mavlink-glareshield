#!/usr/bin/env python3
"""
Generates src/mavlink/dialect.generated.ts (names, CRC extras) and dialectFields.generated.ts (field tables) from a
MAVLink dialect XML (with its includes): every message's name, CRC
extra, and fields in wire order (type, array length, units, extension or not). The app's parser uses the CRC extras to
accept every message of the dialect; the MAVLink Inspector decodes any of them with the field tables.

Use ArduPilot's own definitions, so the app matches the firmware:
  python3 scripts/gen-mavlink-dialect.py ../ardupilot/modules/mavlink/message_definitions/v1.0/ardupilotmega.xml
Needs pymavlink (its generator's XML parser and CRC rules).
"""
import json
import os
import sys

from pymavlink.generator import mavparse

TYPES = {'char', 'int8_t', 'uint8_t', 'uint8_t_mavlink_version', 'int16_t', 'uint16_t', 'int32_t', 'uint32_t', 'int64_t', 'uint64_t', 'float', 'double'}


def load(path, seen):
    path = os.path.abspath(path)
    if path in seen:
        return []
    seen.add(path)
    x = mavparse.MAVXML(path, wire_protocol_version='2.0')
    out = []
    for inc in x.include:
        out += load(os.path.join(os.path.dirname(path), inc), seen)
    return out + [x]


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    xmls = load(sys.argv[1], set())
    messages = {}
    for x in xmls:
        for m in x.message:
            base = m.extensions_start if m.extensions_start is not None else len(m.fields)
            ext_names = {f.name for f in m.fields[base:]}
            fields = []
            for f in m.ordered_fields:
                t = f.type
                if t not in TYPES:
                    sys.exit(f'{m.name}.{f.name}: unknown type {t}')
                if t == 'uint8_t_mavlink_version':
                    t = 'uint8_t'
                units = (f.units or '').strip('[]')
                fields.append([f.name, t, f.array_length or 0, units, 1 if f.name in ext_names else 0])
            messages[m.id] = [m.name, m.crc_extra, fields]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    dialect = os.path.basename(sys.argv[1])
    head = '// Generated by scripts/gen-mavlink-dialect.py from ' + dialect + ' (with its includes). Do not edit.\n'
    # Names and CRC extras: small, for the parser (main bundle).
    out = os.path.join(root, 'src', 'mavlink', 'dialect.generated.ts')
    with open(out, 'w') as f:
        f.write(head)
        f.write('// Every message: [name, CRC extra]. The field tables are in dialectFields.generated.ts (the Inspector).\n\n')
        f.write('export const DIALECT_NAME = ' + json.dumps(dialect) + ';\n\n')
        f.write('export const DIALECT_MESSAGES: Record<number, [string, number]> = {\n')
        for mid in sorted(messages):
            f.write(f'  {mid}: {json.dumps(messages[mid][:2], separators=(",", ":"))},\n')
        f.write('};\n')
    # Field tables: loaded only with the MAVLink Inspector.
    fields_out = os.path.join(root, 'src', 'mavlink', 'dialectFields.generated.ts')
    with open(fields_out, 'w') as f:
        f.write(head)
        f.write('// Every message\'s fields in wire order: [name, type, array length (0 = not an array), units, 1 if an extension].\n\n')
        f.write('export type DialectField = [string, string, number, string, 0 | 1];\n\n')
        f.write('export const DIALECT_FIELDS: Record<number, DialectField[]> = {\n')
        for mid in sorted(messages):
            f.write(f'  {mid}: {json.dumps(messages[mid][2], separators=(",", ":"))},\n')
        f.write('};\n')
    print(f'{len(messages)} messages -> {out}')


if __name__ == '__main__':
    main()
